"""Run character regressions sequentially; a passing suite is not a phase gate.

Use --offline during native Studio capture. Godot suites require Studio closed.
Existing empirical calibration is deliberately not regenerated by this runner.
"""
import argparse
import csv
import datetime
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import time
import uuid

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_GODOT = ROOT / ".codex-tools/godot-4.7/Godot_v4.7-stable_win64_console.exe"
VM_FIXTURE = "res://tools/character_parity/validate_enum_vm_boundary.gd"


def studio_running():
    if os.name != "nt":
        return False
    result = subprocess.run(["tasklist", "/FI", "IMAGENAME eq RobloxStudioBeta.exe", "/FO", "CSV", "/NH"],
                            capture_output=True, text=True, errors="replace", timeout=15)
    if result.returncode:
        raise RuntimeError("Cannot establish whether Studio is running")
    return any(row and row[0].lower() == "robloxstudiobeta.exe" for row in csv.reader(result.stdout.splitlines()))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--offline", action="store_true", help="Python/own Luau source checks only; no Godot")
    parser.add_argument("--godot", type=Path, default=DEFAULT_GODOT)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--baseline", type=Path, help="Optional local dirty snapshot, read-only")
    parser.add_argument("--allow-baseline-source", action="append", default=[],
                        help="Exact additional reviewed source path changed since that snapshot")
    parser.add_argument("--only", action="append", default=[], help="Run only these named checks; repeat for several")
    args = parser.parse_args()
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    out = (args.output or ROOT / f".codex-tmp/character_parity/suites/{stamp}-{uuid.uuid4().hex[:6]}").resolve()
    out.mkdir(parents=True, exist_ok=False)
    jobs = [
        ("python-analysis", [sys.executable, "-m", "unittest", "discover", "-s", "tools/character_parity", "-p", "test_*.py"]),
        ("python-transport", [sys.executable, "-m", "unittest", "discover", "-s", "tools/roblox_character_experiments", "-p", "test_*.py"]),
        ("enum-schema", [sys.executable, "tools/character_parity/review_enum_schema.py"]),
    ]
    if args.baseline:
        baseline_command = [sys.executable, "tools/character_parity/verify_baseline.py", str(args.baseline),
                            "--allow", "autoload/lua_script_engine.gd"]
        for source in args.allow_baseline_source:
            baseline_command.extend(["--allow", source])
        jobs.append(("protected-baseline", baseline_command))
    if not args.offline:
        if studio_running():
            raise SystemExit("BLOCKED: close Roblox Studio before running the Godot suite; no process was stopped")
        if not args.godot.is_file():
            raise SystemExit("BLOCKED: supply an existing Godot 4.7 executable with --godot")
        scripts = [
            ("enum-kernel", "res://tools/character_parity/validate_enumitem_prototype.gd", []),
            ("enum-vm-parity-first", VM_FIXTURE, ["--parity-first"]),
            ("enum-vm-legacy-first", VM_FIXTURE, []),
            ("player-contract", "res://tools/validate_humanoid_player_contract.gd", []),
            ("npc-contract", "res://tools/validate_humanoid_npc_contract.gd", []),
            ("luau-scheduling", "res://tools/validate_luau_scheduling.gd", []),
            ("native-callback-guard", "res://tools/validate_luau_native_callback_guard.gd", []),
            ("property-cache", "res://tools/validate_luau_property_cache.gd", []),
        ]
        for name, script, flags in scripts:
            command = [str(args.godot), "--headless", "--path", str(ROOT), "--script", script, "--", *flags]
            if name.startswith("enum-"):
                command.append(f"--report={out / (name + '.json')}")
            jobs.append((name, command))
    omitted = []
    if args.only:
        unknown = sorted(set(args.only) - {name for name, _ in jobs})
        if unknown:
            raise SystemExit("Unknown/unavailable checks: " + ", ".join(unknown))
        omitted = [name for name, _ in jobs if name not in args.only]
        jobs = [(name, command) for name, command in jobs if name in args.only]
    results = []
    for name, command in jobs:
        started = time.monotonic()
        try:
            result = subprocess.run(command, cwd=ROOT, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                    timeout=180, text=True, encoding="utf-8", errors="replace")
            log, code = result.stdout, result.returncode
        except subprocess.TimeoutExpired as exc:
            data = exc.stdout or b""
            log = data.decode("utf-8", errors="replace") if isinstance(data, bytes) else data
            code = None
        (out / (name + ".log")).write_text(log, encoding="utf-8")
        runtime_error = bool(re.search(r"(?m)^(SCRIPT ERROR:|ERROR:|CrashHandler:)", log))
        status = "BLOCKED" if code is None else "PASS" if code == 0 and not runtime_error else "FAIL"
        results.append({"name": name, "status": status, "exit_code": code, "runtime_error": runtime_error,
                        "elapsed_s": round(time.monotonic() - started, 3), "log": str(out / (name + ".log"))})
        print(f"{name}: {status}", flush=True)
    report = {"schema": 1, "started_utc": stamp, "scope": "local regression suite; no full character/map/network parity claim",
              "suite": "offline" if args.offline else "local-godot", "checks": results,
              "status": "PASS" if all(r["status"] == "PASS" for r in results) else "FAIL",
              "not_selected": omitted,
              "not_run": ["old/new peer protocol matrix", "native visual comparison", "Android", "20 players/100 NPC load", "historical calibration regeneration"]}
    (out / "report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Report: {out / 'report.json'}")
    raise SystemExit(0 if report["status"] == "PASS" else 1)


if __name__ == "__main__":
    main()
