def add_figure(doc: Document, templates: dict[str, Paragraph], description: str, caption: str, width_cm: float = 14.4) -> None:
    append_text_like(doc, templates["body"], description)
    image_paragraph = append_text_like(doc, templates["picture"], "")
    image_paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    image_run = image_paragraph.add_run()
    image_run.add_picture(str(create_placeholder_image()), width=Cm(width_cm))
    caption_paragraph = append_text_like(doc, templates["caption"], caption)
    caption_paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER


def add_front_matter(doc: Document, example: Document) -> None:
    template = example.paragraphs
    replacements = {
        13: "студента 1 курса группы [номер группы]",
        16: "[ФИО студента]",
    }
    toc_by_index = {36 + i: f"{title}\t{page}" for i, (title, page) in enumerate(TOC_ENTRIES)}
    replacements.update(toc_by_index)
    for index in range(0, 51):
        src = template[index]
        if index in replacements:
            paragraph = append_text_like(doc, src, replacements[index])
            if index == 16:
                for run in paragraph.runs:
                    run.font.color.rgb = RGBColor(192, 0, 0)
        else:
            append_raw_paragraph(doc, src)
        if index == 23 and example.tables:
            append_raw_table(doc, example.tables[0])


def add_body(doc: Document, example: Document) -> None:
    templates = {
        "heading": example.paragraphs[51],
        "body": example.paragraphs[52],
        "list": example.paragraphs[54],
        "caption": example.paragraphs[286],
        "picture": example.paragraphs[194],
        "page_break": example.paragraphs[305],
    }
    for title, blocks in SECTIONS:
        append_text_like(doc, templates["heading"], title)
        for kind, *values in blocks:
            if kind == "p":
                append_text_like(doc, templates["body"], values[0])
            elif kind == "l":
                append_text_like(doc, templates["list"], values[0])
            elif kind == "fig":
                add_figure(doc, templates, values[0], values[1])
    add_page_break_like(doc, templates["page_break"])
    append_text_like(doc, templates["heading"], "Список литературы")
    for item in LITERATURE:
        append_text_like(doc, templates["body"], item)


