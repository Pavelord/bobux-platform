def clear_body_keep_section(doc: Document) -> None:
    body = doc._element.body
    sect_pr = body.sectPr
    for child in list(body):
        if child is not sect_pr:
            body.remove(child)


def append_raw_paragraph(doc: Document, source: Paragraph) -> Paragraph:
    new_p = deepcopy(source._p)
    doc._element.body.insert(-1, new_p)
    return Paragraph(new_p, doc._body)


def append_raw_table(doc: Document, source_table) -> None:
    new_tbl = deepcopy(source_table._tbl)
    for text_node in new_tbl.xpath(".//w:t"):
        if "Глинчиков" in text_node.text:
            text_node.text = "[ФИО руководителя]"
    doc._element.body.insert(-1, new_tbl)


def copy_run_rpr(source: Paragraph, target_run) -> None:
    for run in source.runs:
        r_pr = run._r.rPr
        if r_pr is not None:
            target_run._r.insert(0, deepcopy(r_pr))
            return
    target_run.font.name = "Times New Roman"
    target_run._element.rPr.rFonts.set(qn("w:ascii"), "Times New Roman")
    target_run._element.rPr.rFonts.set(qn("w:hAnsi"), "Times New Roman")
    target_run.font.size = Pt(12)


def append_text_like(doc: Document, source: Paragraph, text: str = "") -> Paragraph:
    new_p = deepcopy(source._p)
    for child in list(new_p):
        if child.tag != qn("w:pPr"):
            new_p.remove(child)
    doc._element.body.insert(-1, new_p)
    paragraph = Paragraph(new_p, doc._body)
    if text:
        run = paragraph.add_run(text)
        copy_run_rpr(source, run)
    return paragraph


def set_text_like(paragraph: Paragraph, source: Paragraph, text: str) -> None:
    for child in list(paragraph._p):
        if child.tag != qn("w:pPr"):
            paragraph._p.remove(child)
    if text:
        run = paragraph.add_run(text)
        copy_run_rpr(source, run)


def set_times(run, size: float = 12, bold: bool | None = None, color: RGBColor | None = None) -> None:
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:ascii"), "Times New Roman")
    run._element.rPr.rFonts.set(qn("w:hAnsi"), "Times New Roman")
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold
    if color is not None:
        run.font.color.rgb = color


def add_page_break_like(doc: Document, source: Paragraph) -> None:
    paragraph = append_text_like(doc, source, "")
    paragraph.add_run().add_break(WD_BREAK.PAGE)


def create_placeholder_image(width: int = 1400, height: int = 1040) -> Path:
    PLACEHOLDER_DIR.mkdir(parents=True, exist_ok=True)
